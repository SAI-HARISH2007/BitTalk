def authenticate_student(enrollment, name_input):
    """
    Authenticate student with partial name matching.
    
    Args:
        enrollment: Student enrollment number
        name_input: Full or partial name
    
    Returns:
        tuple: (success: bool, result: str)
    """
    enrollment = enrollment.strip().upper()
    name_input = name_input.strip().upper()
    
    # Check enrollment exists
    if enrollment not in STUDENTS:
        return False, "Invalid enrollment number"
    
    # Get official name
    correct_name = STUDENTS[enrollment]
    
    # Empty check
    if not name_input:
        return False, "Name cannot be empty"
    
    # Split into words
    input_words = name_input.split()
    correct_words = correct_name.upper().split()
    
    # Verify each input word
    for input_word in input_words:
        # Minimum 3 characters
        if len(input_word) < 3:
            return False, "Each name word must be at least 3 characters"
        
        # Check if word matches
        match_found = False
        for correct_word in correct_words:
            if correct_word.startswith(input_word) or input_word in correct_word:
                match_found = True
                break
        
        if not match_found:
            return False, "Name does not match enrollment number"
    
    return True, correct_name


